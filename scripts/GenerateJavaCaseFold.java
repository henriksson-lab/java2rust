// The checked-in table targets the JDK used by the corpus differential oracle.
class GenerateJavaCaseFold {
    static void row(int start, int end, int delta) {
        System.out.printf("    (0x%x, 0x%x, %d),%n", start, end, delta);
    }
    public static void main(String[] args) {
        System.out.println("// Generated by scripts/GenerateJavaCaseFold.java; JDK " + System.getProperty("java.version"));
        System.out.println("// Character.toLowerCase(Character.toUpperCase(codePoint)); identity omitted.");
        System.out.println("const JAVA_SIMPLE_CASE_FOLD: &[(u32, u32, i32)] = &[");
        int start = -1, end = -1, delta = 0;
        for (int point = 0; point <= Character.MAX_CODE_POINT; point++) {
            int next = Character.toLowerCase(Character.toUpperCase(point)) - point;
            if (next != 0 && start >= 0 && point == end + 1 && next == delta) {
                end = point;
            } else {
                if (start >= 0) row(start, end, delta);
                start = next == 0 ? -1 : point;
                end = point;
                delta = next;
            }
        }
        if (start >= 0) row(start, end, delta);
        System.out.println("];");
    }
}
