count_concrete_none_assignments() {
  local path="$1"
  grep -R -E '= None;' "$path" \
    | grep -v -E 'let mut [A-Za-z_][A-Za-z0-9_]*: Option<.*> = None;' \
    | wc -l \
    | tr -d ' '
}

count_concrete_none_assignment_files() {
  local path="$1"
  grep -R -l -E '= None;' "$path" \
    | while IFS= read -r candidate; do
        if grep -E '= None;' "$candidate" \
          | grep -q -v -E 'let mut [A-Za-z_][A-Za-z0-9_]*: Option<.*> = None;'; then
          printf '%s\n' "$candidate"
        fi
      done \
    | wc -l \
    | tr -d ' '
}

translate_one() {
  local index="$1"
  local java_file="$2"
  local binary="$3"
  local out_dir="$4"
  local generated_dir="$5"
  local log_dir="$6"
  shift 6
  local translate_args=("$@")
  local stem
  stem="$(printf '%05d_%s' "$index" "$(basename "${java_file%.java}")")"
  stem="$(printf '%s' "$stem" | tr -c 'A-Za-z0-9_' '_')"
  local rust_path="$generated_dir/$stem.rs"
  local log_path="$log_dir/$stem.stderr"
  local tmp_path="$out_dir/$stem.rs.tmp"
  local status="ok"
  if "$binary" "${translate_args[@]}" "$java_file" > "$tmp_path" 2> "$log_path"; then
    mv "$tmp_path" "$rust_path"
  else
    status="failed"
    mv "$tmp_path" "$rust_path" 2>/dev/null || touch "$rust_path"
  fi
  local diagnostics invalid_patterns
  diagnostics="$(wc -l < "$log_path" | tr -d ' ')"
  invalid_patterns="$(
    {
      grep -E 'compile_error!|downcast::<.*>\(\)\.expect\("invalid Java cast"\)|\.add_all\(|\.size\(|\.put\(|unsupported Java lambda|unsupported Java method reference|unsupported Java array creation' "$rust_path" || true
      grep -E '= None;' "$rust_path" \
        | grep -v -E 'let mut [A-Za-z_][A-Za-z0-9_]*: Option<.*> = None;' || true
    } | wc -l | tr -d ' '
  )"
  printf "%s\t%s\t%s\t%s\t%s\n" "$java_file" "$rust_path" "$status" "$diagnostics" "$invalid_patterns"
}

export -f translate_one

