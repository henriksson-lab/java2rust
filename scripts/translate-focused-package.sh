strip_shared_support_items() {
  local rust_path="$1"
  awk '
    BEGIN { in_prelude = 1; pending = "" }
    in_prelude {
      if ($0 ~ /^#\[derive/) {
        pending = pending $0 "\n"
        next
      }
      if ($0 ~ /^pub[[:space:]]+(struct|enum)[[:space:]]+[A-Za-z_][A-Za-z0-9_]*/) {
        name = $3
        sub(/[;{(<].*/, "", name)
        if (name == "JavaException" || name == "Path" || name == "URI" || name == "File" || name == "IOUtils") {
          pending = ""
          next
        }
        printf "%s", pending
        pending = ""
        print
        in_prelude = 0
        next
      }
      next
    }
    { print }
  ' "$rust_path" > "$rust_path.stripped"
  mv "$rust_path.stripped" "$rust_path"
}

